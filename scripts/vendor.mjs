// Copies browser dependencies into public/ (the site has no build step).
// Run after changing gsap or lucide-static versions: `npm run vendor`.
import { readFileSync, writeFileSync, copyFileSync } from 'node:fs';

copyFileSync('node_modules/gsap/dist/gsap.min.js', 'public/vendor/gsap.min.js');

const ICONS = ['sparkles', 'check', 'arrow-right', 'shield-check', 'log-out', 'user', 'crown', 'menu', 'x', 'chevron-down'];
const ver = JSON.parse(readFileSync('node_modules/lucide-static/package.json', 'utf8')).version;
const body = (name) => readFileSync(`node_modules/lucide-static/icons/${name}.svg`, 'utf8')
  .replace(/<!--[\s\S]*?-->/g, '').match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1].replace(/\s+/g, ' ').trim();
const out = `// Lucide icons (lucide-static v${ver}, ISC license). Generated by scripts/vendor.mjs; do not edit.
const PATHS = ${JSON.stringify(Object.fromEntries(ICONS.map((n) => [n, body(n)])), null, 1)};

// Returns an inline <svg> element; decorative by default (aria-hidden).
export function icon(name, cls = '') {
  const wrap = document.createElement('span');
  wrap.innerHTML = \`<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false" class="lucide lucide-\${name} \${cls}">\${PATHS[name]}</svg>\`;
  return wrap.firstElementChild;
}
`;
writeFileSync('public/js/icons.js', out);
console.log('vendored gsap + %d icons', ICONS.length);
